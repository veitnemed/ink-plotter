def demo_glyphs():
    """Return an independent demo font dictionary."""
    font = {}
    for row in DEMO.strip().splitlines():
        char, drawing = row[0], row[2:]
        font[char] = [[tuple(map(float, pair.split(","))) for pair in stroke.split()]
                      for stroke in drawing.split("/")]
    return font
